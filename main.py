import json
import os
from kivymd.app import MDApp
from kivymd.uix.boxlayout import MDBoxLayout
from kivymd.uix.button import MDFlatButton, MDRaisedButton
from kivymd.uix.dialog import MDDialog
from kivymd.uix.list import MDList, OneLineListItem
from kivymd.uix.screen import MDScreen
from kivymd.uix.scrollview import MDScrollView
from kivymd.uix.textfield import MDTextField
from kivymd.uix.toolbar import MDTopAppBar


class ApplicationChants(MDApp):

    def build(self):
        # Configuration du thème
        self.theme_cls.primary_palette = "Blue"
        self.theme_cls.theme_style = "Light"

        # Gestion du fichier de favoris
        self.fichier_favoris = "favoris.json"
        self.favoris_ids = self.charger_favoris()

        # Charger la liste des chants depuis le fichier JSON
        try:
            with open("chants.json", "r", encoding="utf-8") as fichier:
                self.chants = json.load(fichier)
        except FileNotFoundError:
            self.chants = []

        # Construction de l'interface graphique
        self.ecran_principal = MDScreen()
        layout_global = MDBoxLayout(orientation="vertical")

        # 1. Barre de titre supérieure
        self.barre_titre = MDTopAppBar(
            title="Chants Catholiques",
            elevation=2,
            right_action_items=[
                ["brightness-6", lambda x: self.basculer_theme()]
            ],
        )
        layout_global.add_widget(self.barre_titre)

        # 2. Boutons de Filtre (Tous les chants / Mes Favoris)
        layout_filtres = MDBoxLayout(
            orientation="horizontal",
            size_hint_y=None,
            height="50dp",
            padding=["10dp", "5dp"],
            spacing="10dp",
        )
        self.btn_tous = MDRaisedButton(
            text="Tous les chants",
            on_release=lambda x: self.afficher_chants(self.chants),
        )
        self.btn_favoris = MDRaisedButton(
            text="Mes Favoris",
            on_release=lambda x: self.afficher_favoris_seulement(),
        )
        layout_filtres.add_widget(self.btn_tous)
        layout_filtres.add_widget(self.btn_favoris)
        layout_global.add_widget(layout_filtres)

        # 3. Champ de recherche dynamique
        self.champ_recherche = MDTextField(
            hint_text="Rechercher par titre, catégorie ou paroles...",
            size_hint_x=0.95,
            pos_hint={"center_x": 0.5},
        )
        self.champ_recherche.bind(text=self.filtrer_liste)
        layout_global.add_widget(self.champ_recherche)

        # 4. Liste défilante des chants
        defilement = MDScrollView()
        self.liste_widgets = MDList()
        defilement.add_widget(self.liste_widgets)
        layout_global.add_widget(defilement)

        self.ecran_principal.add_widget(layout_global)

        # Affichage initial au lancement
        self.afficher_chants(self.chants)

        return self.ecran_principal

    # --- FONCTIONS DE GESTION DES FAVORIS ---
    def charger_favoris(self):
        if os.path.exists(self.fichier_favoris):
            try:
                with open(self.fichier_favoris, "r") as f:
                    return json.load(f)
            except Exception:
                return []
        return []

    def sauvegarder_favoris(self):
        with open(self.fichier_favoris, "w") as f:
            json.dump(self.favoris_ids, f)

    def toggle_favori(self, chant):
        if chant["id"] in self.favoris_ids:
            self.favoris_ids.remove(chant["id"])
        else:
            self.favoris_ids.append(chant["id"])
        self.sauvegarder_favoris()
        self.afficher_chants(self.chants)

    # --- FONCTIONS D'AFFICHAGE ET DE FILTRAGE ---
    def afficher_chants(self, liste_a_afficher):
        self.liste_widgets.clear_widgets()
        for chant in liste_a_afficher:
            est_fav = chant["id"] in self.favoris_ids
            indicateur_fav = "[FAV] " if est_fav else ""

            item = OneLineListItem(
                text=f"{indicateur_fav}{chant['titre']} - ({chant['categorie']})",
                on_release=lambda x, c=chant: self.afficher_paroles(c),
            )
            self.liste_widgets.add_widget(item)

    def filtrer_liste(self, instance, texte):
        recherche = texte.lower().strip()
        if not recherche:
            self.afficher_chants(self.chants)
            return

        resultats = [
            c
            for c in self.chants
            if recherche in c["titre"].lower()
            or recherche in c["categorie"].lower()
            or recherche in c["paroles"].lower()
        ]
        self.afficher_chants(resultats)

    def afficher_favoris_seulement(self):
        mes_favs = [c for c in self.chants if c["id"] in self.favoris_ids]
        self.afficher_chants(mes_favs)

    # --- BASCHULEMENT DU THÈME (MODE NUIT) ---
    def basculer_theme(self):
        if self.theme_cls.theme_style == "Light":
            self.theme_cls.theme_style = "Dark"
        else:
            self.theme_cls.theme_style = "Light"

    # --- AFFICHAGE DES PAROLES ---
    def afficher_paroles(self, chant):
        def fermer_dialogue(instance):
            self.dialogue.dismiss()

        def gerer_favori(instance):
            self.toggle_favori(chant)
            self.dialogue.dismiss()

        est_fav = chant["id"] in self.favoris_ids
        texte_btn_fav = (
            "Retirer des Favoris" if est_fav else "Ajouter aux Favoris"
        )

        self.dialogue = MDDialog(
            title=chant["titre"],
            text=chant["paroles"],
            buttons=[
                MDFlatButton(text=texte_btn_fav, on_release=gerer_favori),
                MDFlatButton(text="FERMER", on_release=fermer_dialogue),
            ],
        )
        self.dialogue.open()


if __name__ == "__main__":
    ApplicationChants().run()
